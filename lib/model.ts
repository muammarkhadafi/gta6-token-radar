// Launch Desk's model for token-radar-01: a comparables-calibrated implied value.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// early radar: pre-token protocols below the floor that are real launch candidates. A protocol is a
// launch candidate when it records no token, is not an exchange, carries no version marker in its
// name, and is not a wrapped, staked or bridged product of a token that already trades. The
// snapshot's live-token protocols are kept apart and shown at the market's own values, never mixed
// into the ranked board.
//
// The implied value is calibrated from the snapshot itself, never from a fixed multiple and never
// from a hand-kept list of names. For each category, the model takes the median market-cap-to-TVL
// ratio of the category's tokenized protocols (its comparables), shrinks it toward the global median
// where the category has few peers, and clamps it to a sane band. Then:
//
//   base         = tvl_usd x effective_multiple(category)
//   growth       = 1 + 0.35 x tanh(change_7d / 50)          (dampened: a +4000% week cannot 40x a value)
//   maturity     = 0.75 + 0.25 x ln(1 + age) / ln(1 + 1095) (log curve: age helps, with diminishing returns)
//   chains       = 1 + 0.05 x min(chains - 1, 4)            (a protocol live on more chains reaches more users)
//   implied      = max(1, round(base x growth x maturity x chains))
//
// A protocol with no listed_at falls back to the snapshot's own median age. A protocol with no
// reported 7-day change is scored at neutral growth. No protocol name is ever special-cased: the
// same function scores every row, and the dashboard shows the calibration table it ran on.

